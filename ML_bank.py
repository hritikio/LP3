import pandas as pd
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler

df=pd.read_csv("Churn_Modelling.csv")
df.drop(["Surname","CustomerId","RowNumber"],axis=1)
df=pd.get_dummies(df,drop_first=True,dtype=int)
# get_dummies() → Converts categorical data into numerical columns.
# drop_first=True → Removes the first category to reduce redundant columns.
# dtype=int → Uses 0 and 1 instead of True and False.

X=df.drop("Exited",axis=1)
Y=df["Exited"]

X_train,X_test,Y_train,Y_test=train_test_split(X,Y,test_size=0.2,random_state=42)
scaler=StandardScaler()
X_train=scaler.fit_transform(X_train)
# fit finds each column’s average and spread from the training data, and transform converts the values to a common scale.
#  We normalize because Balance (huge numbers) and Age (small numbers) would otherwise confuse the network.
X_test=scaler.transform(X_test)
# Scales the test data using the same numbers learned from training data.
# Only transform, not fit, because test data must stay unseen.

from sklearn.neural_network import MLPClassifier
from sklearn.metrics import confusion_matrix, accuracy_score
model1 = MLPClassifier(hidden_layer_sizes=(6,),max_iter=500,random_state=42)
# max_iter=500 means train for at most 500 rounds (epochs).
# hidden_layer_sizes=(6,) means one hidden layer with 6 neurons.
# The comma is what makes it a tuple, not the parentheses.

model1.fit(X_train,Y_train)
pred1=model1.predict(X_test)

print("Accuracy:", accuracy_score(Y_test, pred1))
print(confusion_matrix(Y_test, pred1))

# Improved model
model2 = MLPClassifier(hidden_layer_sizes=(16,8),alpha=0.001,early_stopping=True,max_iter=500,random_state=42)
# hidden_layer_sizes=(16, 8): two hidden layers (16 neurons, then 8), so it can learn more complex patterns.
# alpha=0.001: a regularization value. It stops the weights from becoming too large, which reduces overfitting.
# early_stopping=True: keeps 10% of the training data aside and stops training automatically when the score stops improving,
#  so the model doesn’t overfit.

model2.fit(X_train,Y_train)
pred2=model2.predict(X_test)

print("Improved Accuracy:", accuracy_score(Y_test, pred2))
print(confusion_matrix(Y_test, pred2))
#Accuracy for model 2 increased wehn more layer and early stop was introduced

