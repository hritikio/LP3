import pandas as pd
from sklearn.model_selection import train_test_split
df=pd.read_csv("emails.csv")

X=df.drop(["Email No.","Prediction"],axis=1)
# the axis=1 means it is colums , 0 is for rows
# we remove email no and prediction column rest is there in x
Y=df["Prediction"]
#  Y is column having the actual answer that we will predict

X_train,X_test,Y_train,Y_test=train_test_split(X,Y,test_size=0.2,random_state=42)
# test size is 20%
# 80% of emails have the answers from which model runs (X_train,Y_train)

from sklearn.neighbors import KNeighborsClassifier
from sklearn.metrics import confusion_matrix,accuracy_score,classification_report

knn=KNeighborsClassifier(n_neighbors=5)
# Creates a KNN model that looks at the 5 nearest emails (K = 5). Nothing is learned yet. It’s an empty model.

knn.fit(X_train,Y_train)
# model is training on training data

knn_pred= knn.predict(X_test)
# For each test email, KNN finds the 5 most similar training emails and votes.
# The results (0s and 1s) are stored in knn_pred. The model has not seen the real answers (y_test) here.

print("Accuracy Score :", accuracy_score(Y_test,knn_pred))
print(confusion_matrix(Y_test,knn_pred))
# tn, fp, fn, tp
print(classification_report(Y_test,knn_pred))
# Prints precision, recall, and F1 for each class:
# Precision: of the emails called spam, how many really were?
# Recall: of all real spam, how many did we catch?
# F1: a balance of the two.

from sklearn.svm import SVC

svm=SVC(kernel="linear")
# SVC(kernel="linear") creates a machine learning classifier that will learn to separate categories using a
#  straight-line decision boundary when you train it with .fit().

svm.fit(X_train,Y_train)
svm_pred=svm.predict(X_test)
# learn from the training data, then predict on the test data.

print("SVM accuracy",accuracy_score(Y_test,svm_pred))
print(confusion_matrix(Y_test,svm_pred))
print(classification_report(Y_test,svm_pred))

#conclusion - SVM is with higher accuracy