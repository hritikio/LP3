import pandas as pd
df=pd.read_csv("diabetes.csv")
print(df.head())
print(df.shape)
print(df['Outcome'].value_counts())

from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler
X=df.drop('Outcome',axis=1)
Y=df['Outcome']

X_train,X_test,Y_train,Y_test=train_test_split(X,Y,test_size=0.2,random_state=42)
# 20 percent is testing data

scaler =StandardScaler()
X_train=scaler.fit_transform(X_train)
# Two steps in one:

# fit: looks at the training data and finds each column’s average and spread.
# transform: uses those numbers to convert every value to a common scale (average 0, spread 1).
X_test=scaler.transform(X_test)
# Scales the test data using the same numbers learned from training data.
# Only transform here, not fit, because test data must stay unseen.

from sklearn.neighbors import KNeighborsClassifier
from sklearn.metrics import accuracy_score, confusion_matrix, precision_score, recall_score

knn=KNeighborsClassifier(n_neighbors=5)
# Creates a KNN model with K = 5, meaning it will look at the 5 nearest patients. Nothing is learned yet.

knn.fit(X_train,Y_train)
# The training step. It gives the model the training patients and their answers. KNN simply stores them.

y_pred=knn.predict(X_test)

print("Confusion Matrix ",confusion_matrix(Y_test,y_pred))
print("Accuracy :",accuracy_score(Y_test,y_pred))
print("Precision :",precision_score(Y_test,y_pred))
print("Recall :",recall_score(Y_test,y_pred))
print("Error Rate :",1-accuracy_score(Y_test,y_pred))

